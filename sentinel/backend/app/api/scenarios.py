def _load_esa_scenarios_from_disk() -> list[dict[str, Any]]:
    """Dynamically load ESA crash dump JSONs from data/esa_crash_dumps/.

    Returns additional scenario dicts built from compact sentinel-only
    crash dump files. These supplement the hardcoded id_109 above.
    Errors are logged but never crash the server.

    Provenance is read from each file's own ``provenance`` field and is never
    assumed. A file that does not declare its provenance is surfaced as
    UNKNOWN, not as REAL. This function previously stamped every file it
    loaded as "Real ESA Telemetry", which mislabelled files whose numeric
    values were synthesized from real metadata.
    """
    esa_dir = os.path.join(
        os.path.dirname(__file__), "..", "..", "data", "esa_crash_dumps"
    )
    if not os.path.isdir(esa_dir):
        return []

    extra: list[dict[str, Any]] = []
    for fname in sorted(os.listdir(esa_dir)):
        if not fname.endswith("_sentinel_only.json"):
            continue
        # Skip id_109 — already hardcoded above
        if "id_109" in fname:
            continue
        try:
            with open(os.path.join(esa_dir, fname), "r", encoding="utf-8") as fh:
                dump = json.load(fh)

            # Derive the display fields from the file's declared provenance.
            # describe() normalizes unknown/missing values away from REAL.
            resolved = describe(dump)
            dump.update(resolved)

            if resolved["provenance"] == Provenance.UNKNOWN.value:
                logger.warning(
                    "ESA scenario %s declares no provenance — surfacing as UNKNOWN",
                    fname,
                )

            extra.append(dump)
        except Exception as exc:
            logger.warning("Failed to load ESA scenario %s: %s", fname, exc)

    return extra


def get_all_scenarios() -> list[dict[str, Any]]:
    """Return preset + dynamically loaded ESA scenarios.

    This is the preferred public API. Falls back to just presets
    if ESA loading fails.

    Every returned scenario is guaranteed to carry a ``provenance`` code and a
    ``source_type`` label derived from it, so the frontend never has to guess
    and can never be handed a "real" label for generated numbers.
    """
    presets = get_preset_scenarios()
    for scenario in presets:
        scenario.update(describe(scenario))
        # Phase 5: bounds come from the channel dictionary, not from literals
        # repeated in this file.
        _fill_bounds_from_dictionary(scenario)

    try:
        esa_extra = _load_esa_scenarios_from_disk()
    except Exception as exc:
        logger.warning("ESA dynamic loader failed: %s", exc)
        return presets

    return presets + esa_extra

