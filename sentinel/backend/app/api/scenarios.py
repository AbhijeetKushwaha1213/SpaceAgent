def _fill_bounds_from_dictionary(scenario: dict[str, Any]) -> dict[str, Any]:
    """Fill each legacy telemetry row's bounds from the channel dictionary.

    Phase 5. The preset scenarios repeated ``nominal_min`` / ``nominal_max`` on
    every reading — 27 literal pairs across the six presets, all of them copies of
    the detector's table. They happened to agree with it, but nothing checked
    that, and a scenario carrying a stale bound would have made the detector
    report a violation the operator could not explain from the catalogue.

    Bounds now come from ``app.ingest.channel_dict.hard_limits()``, the same
    source the detector compares against, so a scenario cannot disagree with the
    detector about where a limit is.

    A row for a channel the dictionary does not know keeps whatever bounds it
    carries, and gains none. Nothing is invented for an unknown channel.
    """
    from app.ingest.channel_dict import get_channel

    rows = scenario.get("pre_fault_telemetry")
    if not isinstance(rows, list):
        return scenario

    for row in rows:
        if not isinstance(row, dict):
            continue
        definition = get_channel(row.get("parameter"))
        if definition is None:
            continue
        low, high = definition.hard_limits
        if low is not None:
            row["nominal_min"] = low
        if high is not None:
            row["nominal_max"] = high
        if definition.unit and not row.get("unit"):
            row["unit"] = definition.unit
    return scenario


