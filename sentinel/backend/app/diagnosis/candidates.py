def classify_llm_fault(
    fault_id: object,
    candidate_set: HypothesisSet,
) -> tuple[HypothesisOrigin, Optional[str]]:
    """Classify a fault name the LLM produced.

    Returns ``(origin, note)``:

        LLM_RANKED               the fault is in the deterministic candidate set
        UNSUPPORTED_HYPOTHESIS   it is not

    An unsupported hypothesis is not an error and is not discarded. It is
    labelled, because the alternative — accepting it silently — is what let a
    single model call be both the source and the judge of the diagnosis.

    A fault in the dictionary but rejected by the matcher is still unsupported:
    the matcher rejected it against the evidence, and the model naming it anyway
    does not restore the evidence.
    """
    name = "" if fault_id is None else str(fault_id).strip().upper()
    if not name:
        return HypothesisOrigin.UNSUPPORTED_HYPOTHESIS, (
            "No fault_id supplied, so the hypothesis cannot be matched to any "
            "candidate."
        )

    if name in candidate_set.candidate_fault_ids():
        return HypothesisOrigin.LLM_RANKED, None

    rejection = candidate_set.rejected.get(name)
    if rejection is not None:
        return HypothesisOrigin.UNSUPPORTED_HYPOTHESIS, (
            f"{name} is a known fault but the deterministic engine rejected it "
            f"for this evidence: {rejection}"
        )

    if get_fault(name) is not None:
        return HypothesisOrigin.UNSUPPORTED_HYPOTHESIS, (
            f"{name} is in the fault dictionary but was not generated as a "
            f"candidate from this evidence."
        )

    return HypothesisOrigin.UNSUPPORTED_HYPOTHESIS, (
        f"{name} is not in the SENTINEL fault dictionary. It was produced by "
        f"the language model and has no matched detector evidence."
    )


def engine_status() -> dict:
    """Describe the engine, for the API and tests."""
    from app.diagnosis.fault_dictionary import dictionary_status
    from app.diagnosis.propagation import propagation_status
    from app.diagnosis.signature_match import matching_status

    return {
        "engine_version": HYPOTHESIS_ENGINE_VERSION,
        "uses_llm": False,
        "score_weights": dict(SCORE_WEIGHTS),
        "min_score_to_report": MIN_SCORE_TO_REPORT,
        "max_hypotheses": MAX_HYPOTHESES,
        "score_is_probability": False,
        "score_is_calibrated": False,
        "metric_names": ["top1_candidate_accuracy", "top3_candidate_coverage"],
        "metric_caveat": (
            "These measure whether the deterministic stage puts the labelled "
            "fault into its candidate set. They are NOT diagnosis accuracy, "
            "which would also require the validation and recommendation stages."
        ),
        "origins": [o.value for o in HypothesisOrigin],
        "fault_dictionary": dictionary_status(),
        "propagation": propagation_status(),
        "matching": matching_status(),
    }
