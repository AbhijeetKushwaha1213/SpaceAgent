def generate_hypotheses(
    report: Any,
    crash_dump: Optional[dict[str, Any]] = None,
    max_hypotheses: int = MAX_HYPOTHESES,
    min_score: float = MIN_SCORE_TO_REPORT,
) -> HypothesisSet:
    """Produce a ranked hypothesis set from detector evidence alone.

    Args:
        report: An ``AnomalyReport`` from the Phase 2 detection pipeline.
        crash_dump: The dump, used to learn which channels were examined. Without
            it a channel with no anomaly cannot be told from a channel with no
            reading, which weakens the NOMINAL and contradiction predicates.
        max_hypotheses: Cap on the returned list.
        min_score: Candidates below this are recorded as rejected.

    Returns:
        A ``HypothesisSet``. Deterministic: the same inputs give byte-identical
        output.
    """
    index, matches = match_faults(report, crash_dump)
    ordering = onset_ordering(index.subsystem_onsets)

    scored: list[tuple[float, str, Hypothesis]] = []
    rejected: dict[str, str] = {}

    for match in matches:
        definition = get_fault(match.fault_id)
        if definition is None:  # pragma: no cover — ids come from the dictionary
            continue

        if not match.eligible:
            rejected[match.fault_id] = match.ineligible_reason or "ineligible"
            continue

        propagation, notes, unexplained = _propagation_score(definition, index)
        specificity = _specificity_score(match, definition)
        onset = _onset_score(definition, ordering)

        components = {
            "signature": match.signature_score,
            "propagation": propagation,
            "specificity": specificity,
            "onset": onset,
        }
        score = round(
            sum(SCORE_WEIGHTS[k] * v for k, v in components.items()), 4,
        )

        # A fault with no matched evidence at all is not a candidate, whatever
        # its corroboration terms say. Propagation plausibility alone is not
        # evidence that a fault occurred.
        if not match.matched:
            rejected[match.fault_id] = (
                "no signature matched the detector evidence"
            )
            continue

        if score < min_score:
            rejected[match.fault_id] = (
                f"score {score:.3f} below the reporting threshold {min_score}"
            )
            continue

        detector_ids: list[str] = []
        for record in match.matched:
            detector_ids.extend(record.anomaly_ids)

        scored.append((score, definition.fault_id, Hypothesis(
            hypothesis_id=_hypothesis_id(definition.fault_id, match),
            fault_id=definition.fault_id,
            fault_name=definition.fault_name,
            subsystem=definition.subsystem,
            rank=1,  # assigned after sorting
            score=score,
            supporting_evidence=_to_items(match.matched),
            contradicting_evidence=_to_items(match.contradicted),
            undetermined_evidence=_to_items(match.undetermined),
            affected_channels=list(match.affected_channels),
            timestamps=list(match.timestamps),
            earliest_onset_seconds=match.earliest_onset,
            detector_evidence=sorted(set(detector_ids)),
            origin=HypothesisOrigin.DETERMINISTIC,
            severity=definition.severity.value,
            possible_causes=list(definition.possible_causes),
            recovery_procedure_ids=list(definition.recovery_procedure_ids),
            causal_chain=list(definition.causal_chain),
            score_components=components,
            propagation_notes=notes,
            unexplained_subsystems=unexplained,
            is_evidence_backed=True,
            notes=definition.notes,
        )))

    # Descending score, then fault_id — a deterministic tie-break that does not
    # depend on dictionary order.
    scored.sort(key=lambda item: (-item[0], item[1]))

    hypotheses = [
        h.model_copy(update={"rank": position})
        for position, (_score, _fid, h) in enumerate(scored[:max_hypotheses],
                                                     start=1)
    ]
    for _score, fault_id, _h in scored[max_hypotheses:]:
        rejected[fault_id] = f"ranked below the top {max_hypotheses}"

    warnings: list[str] = []
    if not hypotheses:
        warnings.append(
            "No fault signature matched the detector evidence. This is not a "
            "clean bill of health: it means the evidence does not correspond to "
            "any fault in the dictionary."
        )
    if index.unknown_channels:
        warnings.append(
            f"{len(index.unknown_channels)} anomalous channel(s) have no "
            f"subsystem attribution and cannot support any fault: "
            f"{', '.join(index.unknown_channels[:6])}"
            + ("..." if len(index.unknown_channels) > 6 else "")
        )
    if not ordering.get("determined"):
        warnings.append(
            f"Onset ordering undetermined ({ordering.get('reason')}), so root "
            f"cause was not inferred from timing."
        )
    if len(hypotheses) == 1:
        warnings.append(
            "Only one hypothesis is evidence-backed. A single candidate is not "
            "a confirmed diagnosis; it means the dictionary offers no competing "
            "explanation for this evidence."
        )

    if hypotheses:
        top = hypotheses[0]
        summary = (
            f"{len(hypotheses)} deterministic hypothesis(es) from "
            f"{index.total_anomalies} anomaly(ies); top candidate "
            f"{top.fault_id} at {top.score:.2f} "
            f"({len(top.supporting_evidence)} supporting, "
            f"{len(top.contradicting_evidence)} contradicting)"
        )
    else:
        summary = (
            f"No hypothesis matched {index.total_anomalies} anomaly(ies) across "
            f"{len(index.channels)} channel(s)."
        )

    return HypothesisSet(
        hypotheses=hypotheses,
        considered_fault_ids=[m.fault_id for m in matches],
        rejected=rejected,
        anomalous_subsystems=list(index.anomalous_subsystems),
        unknown_channels=list(index.unknown_channels),
        onset_analysis=ordering,
        warnings=warnings,
        summary=summary,
    )


