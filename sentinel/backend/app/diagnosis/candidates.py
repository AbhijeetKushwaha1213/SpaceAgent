HYPOTHESIS_ENGINE_VERSION = "1.0.0"
"""Version of the ranking logic. Bump when weights or terms change, since stored
hypotheses are only comparable within one version."""


#: Contribution of each term to the final score. Signature evidence dominates
#: because it is the most direct: it is what the detectors actually measured.
#: Propagation and onset are corroboration, and specificity is a tie-breaker
#: between faults with similar coverage.
SCORE_WEIGHTS: dict[str, float] = {
    "signature": 0.60,
    "propagation": 0.20,
    "specificity": 0.13,
    "onset": 0.07,
}

#: Candidates scoring below this are dropped from the ranked set. Set low on
#: purpose: the point of the stage is recall — getting the true fault into the
#: set — so a weak candidate is better retained and ranked last than excluded.
MIN_SCORE_TO_REPORT = 0.05

#: Cap on returned hypotheses. Enough for a differential without burying the
#: operator; the full match list is available separately.
MAX_HYPOTHESES = 8


class HypothesisOrigin(str, Enum):
    """Where a hypothesis came from. The central distinction of Phase 6."""

    DETERMINISTIC = "DETERMINISTIC"
    """Generated by signature matching against detector evidence."""

    LLM_RANKED = "LLM_RANKED"
    """Generated deterministically, then reordered or re-weighted by the LLM.
    Still grounded in matched evidence."""

    UNSUPPORTED_HYPOTHESIS = "UNSUPPORTED_HYPOTHESIS"
    """Named by the LLM but NOT in the deterministic candidate set.

    Retained rather than dropped, because a model may notice a pattern the rules
    do not encode. But it carries no matched evidence, so it must never be
    presented alongside evidence-backed hypotheses without this label. This is
    the mechanism that stops the model inventing a fault and having it treated as
    a finding.
    """


class EvidenceItem(BaseModel):
    """One piece of evidence for or against a hypothesis."""

    model_config = ConfigDict(frozen=True)

    channel: str
    condition: str
    role: str
    state: str
    rationale: str
    detectors: list[str] = Field(default_factory=list)
    severity: Optional[str] = None
    timestamp: Optional[str] = None
    anomaly_ids: list[str] = Field(default_factory=list)
    weight: float = 0.0

    source: str = Field(
        default="TELEMETRY",
        description=(
            "TELEMETRY for a channel predicate, CONTEXT for a predicate over a "
            "recorded context fact such as an array relay position."
        ),
    )
    observed_from: Optional[str] = Field(
        default=None,
        description=(
            "For CONTEXT evidence, the dump field that decided it and the value "
            "it held. None for telemetry, where channel and detectors carry the "
            "provenance."
        ),
    )


class Hypothesis(BaseModel):
    """A ranked fault hypothesis, with every field the Phase 6 spec requires."""

    model_config = ConfigDict(frozen=True)

    hypothesis_id: str = Field(
        ..., description="Stable content-derived id, reproducible across runs",
    )
    fault_id: str
    fault_name: str
    subsystem: str
    rank: int = Field(..., ge=1)
    score: float = Field(..., ge=0.0, le=1.0)

    supporting_evidence: list[EvidenceItem] = Field(default_factory=list)
    contradicting_evidence: list[EvidenceItem] = Field(default_factory=list)
    undetermined_evidence: list[EvidenceItem] = Field(
        default_factory=list,
        description=(
            "Signatures that could not be evaluated because the channel had no "
            "reading. Reported so a reader can tell weak evidence from absent "
            "telemetry."
        ),
    )

    affected_channels: list[str] = Field(default_factory=list)
    timestamps: list[str] = Field(default_factory=list)
    earliest_onset_seconds: Optional[float] = None

    detector_evidence: list[str] = Field(
        default_factory=list,
        description="Anomaly ids from the AnomalyReport backing this hypothesis",
    )

    origin: HypothesisOrigin = HypothesisOrigin.DETERMINISTIC
    severity: str = ""
    possible_causes: list[str] = Field(default_factory=list)
    recovery_procedure_ids: list[str] = Field(default_factory=list)
    causal_chain: list[str] = Field(default_factory=list)

    score_components: dict[str, float] = Field(default_factory=dict)
    score_basis: str = Field(
        default=(
            "Deterministic weighted sum of matched signature evidence, "
            "subsystem propagation plausibility, evidence specificity and onset "
            "ordering. NOT a probability and NOT calibrated against outcomes."
        ),
    )
    propagation_notes: list[str] = Field(default_factory=list)
    unexplained_subsystems: list[str] = Field(
        default_factory=list,
        description=(
            "Subsystems showing anomalies that a fault here cannot account for. "
            "A non-empty list weakens the hypothesis as a single root cause."
        ),
    )
    is_evidence_backed: bool = Field(
        default=True,
        description="False for an UNSUPPORTED_HYPOTHESIS.",
    )
    notes: Optional[str] = None


class HypothesisSet(BaseModel):
    """The complete output of the deterministic engine."""

    model_config = ConfigDict(frozen=True)

    engine_version: str = HYPOTHESIS_ENGINE_VERSION
    fault_dict_version: str = FAULT_DICT_VERSION
    generated_by: str = Field(
        default="deterministic_signature_matching",
        description="Never an LLM. Asserted by test.",
    )
    uses_llm: bool = False

    hypotheses: list[Hypothesis] = Field(default_factory=list)
    considered_fault_ids: list[str] = Field(
        default_factory=list,
        description="Every fault evaluated, including those rejected",
    )
    rejected: dict[str, str] = Field(
        default_factory=dict,
        description="fault_id -> why it was not a candidate",
    )

    anomalous_subsystems: list[str] = Field(default_factory=list)
    unknown_channels: list[str] = Field(
        default_factory=list,
        description=(
            "Anomalous channels with no subsystem attribution, typically "
            "anonymized ESA-ADB channels. They cannot support any fault."
        ),
    )
    onset_analysis: dict[str, Any] = Field(default_factory=dict)
    warnings: list[str] = Field(default_factory=list)
    summary: str = ""

    @property
    def top(self) -> Optional[Hypothesis]:
        return self.hypotheses[0] if self.hypotheses else None

    def top_n_fault_ids(self, n: int) -> list[str]:
        return [h.fault_id for h in self.hypotheses[:n]]

    def candidate_fault_ids(self) -> set[str]:
        """The set an LLM may choose from without being marked unsupported."""
        return {h.fault_id for h in self.hypotheses}


# ═══════════════════════════════════════════════════════════════════════════
# SCORING
# ═══════════════════════════════════════════════════════════════════════════

def _propagation_score(
    definition: FaultDefinition,
    index: EvidenceIndex,
) -> tuple[float, list[str], list[str]]:
    """How well a fault here accounts for every subsystem showing anomalies.

    A fault explaining all of them is a better single root cause than one leaving
    some unaccounted for. When only its own subsystem is anomalous the question
    does not arise and the term is neutral rather than favourable — a single
    subsystem anomaly is not evidence of propagation.
    """
    observed = [s for s in index.anomalous_subsystems if s != "UNKNOWN"]
    if not observed:
        return 0.5, ["No subsystem-attributed anomalies to explain."], []

    if definition.subsystem == "MULTI":
        # A cascade is the better explanation exactly when several subsystems are
        # involved, and a poor one when only one is.
        if len(observed) >= 2:
            return 1.0, [
                f"{len(observed)} subsystems show anomalies "
                f"({', '.join(observed)}), which is what a cascade means."
            ], []
        return 0.1, [
            "Only one subsystem shows anomalies, so a cross-subsystem cascade "
            "is not supported."
        ], []

    explained, unexplained = explained_subsystems(definition.subsystem, observed)

    # Weight each subsystem by the strength of the evidence implicating it rather
    # than counting subsystems equally. Measured reason: on a simulated comms
    # fault, the simulator's injected 5% NaN dropout put one V_bat reading into
    # the anomaly list, which made EPS a subsystem every comms hypothesis had to
    # explain. Counting equally, that single dropout carried the same weight as
    # two hard-limit violations on the comms channels, so telemetry-path noise
    # moved the ranking. See _SUBSYSTEM_EVIDENCE_WEIGHT in signature_match.py.
    strength = index.subsystem_evidence_strength or {}

    def weight_of(subsystem: str) -> float:
        return float(strength.get(subsystem, 1.0))

    notes: list[str] = []
    for subsystem in explained:
        mechanism = explain_path(definition.subsystem, subsystem)
        if mechanism:
            notes.append(f"{definition.subsystem} -> {subsystem}: {mechanism}")
    for subsystem in unexplained:
        notes.append(
            f"{definition.subsystem} -> {subsystem}: no declared propagation "
            f"path, so this fault does not account for the {subsystem} anomaly "
            f"(evidence weight {weight_of(subsystem):.2f})."
        )

    explained_weight = sum(weight_of(s) for s in explained)
    total_weight = sum(weight_of(s) for s in observed)
    if total_weight <= 0.0:
        return 0.5, notes, list(unexplained)

    score = explained_weight / total_weight
    return round(score, 4), notes, list(unexplained)


def _specificity_score(match: SignatureMatch,
                       definition: FaultDefinition) -> float:
    """Fraction of the fault's DISCRIMINATING evidence that matched.

    This is what stops a fault with many generic signatures outranking one whose
    distinctive evidence is present. A fault with no discriminating signatures —
    only MULTI_CASCADE — scores neutral rather than zero, since it is not being
    penalised for a property it declares it does not have.
    """
    discriminating = definition.discriminating_signatures
    if not discriminating:
        return 0.5

    matched_keys = {m.signature_key for m in match.matched}
    hits = sum(1 for s in discriminating if s.key in matched_keys)
    return round(hits / len(discriminating), 4)


def _onset_score(definition: FaultDefinition, ordering: dict[str, Any]) -> float:
    """Whether this fault's subsystem is the earliest to show an anomaly.

    Neutral when the ordering is undetermined. Rewarding a guess would let a
    coin-flip on tied timestamps decide the ranking.
    """
    if not ordering.get("determined"):
        return 0.5
    earliest = ordering.get("earliest")
    if earliest is None:
        return 0.5
    if definition.subsystem == "MULTI":
        return 0.5
    from app.ingest.channel_dict import resolve_subsystem

    if resolve_subsystem(definition.subsystem) is resolve_subsystem(earliest):
        return 1.0
    return 0.25


def _hypothesis_id(fault_id: str, match: SignatureMatch) -> str:
    """Stable id derived from the fault and the evidence that produced it.

    Content-derived rather than sequential, so the same evidence yields the same
    id on a re-run and two runs can be compared.
    """
    material = "|".join([
        fault_id,
        f"{match.signature_score:.4f}",
        ",".join(f"{m.channel}:{m.condition}" for m in match.matched),
        ",".join(f"{m.channel}:{m.condition}" for m in match.contradicted),
    ])
    digest = hashlib.sha256(material.encode("utf-8")).hexdigest()[:12]
    return f"HYP-{digest}"


def _to_items(records: tuple, ) -> list[EvidenceItem]:
    return [
        EvidenceItem(
            channel=r.channel, condition=r.condition, role=r.role,
            state=r.state, rationale=r.rationale, detectors=list(r.detectors),
            severity=r.severity, timestamp=r.timestamp,
            anomaly_ids=list(r.anomaly_ids), weight=r.weight,
            source=getattr(r, "source", "TELEMETRY"),
            observed_from=getattr(r, "observed_from", None),
        )
        for r in records
    ]


