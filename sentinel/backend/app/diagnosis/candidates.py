"""
SENTINEL — Candidate Ranking (app/diagnosis/candidates.py)

Phase 6. Ranks the signature matches into hypotheses, deterministically.

Ranking inputs, all deterministic
---------------------------------
    signature_score       fraction of the fault's evidence weight that matched,
                          minus its contradictions
    propagation_score     whether this fault's subsystem can account for every
                          subsystem showing anomalies, using the declared
                          mechanisms in propagation.py
    specificity           how much DISCRIMINATING evidence matched, so a fault
                          separated by its own distinctive evidence outranks one
                          carried by generic symptoms
    onset_agreement       whether this fault's subsystem is the earliest to show
                          an anomaly, when the timestamps determine an order

No randomness, no model call, no sampling. The same report yields the same ranking.

What a score is not
-------------------
``score`` is a weighted sum of the four terms above, normalised to [0, 1]. It is
NOT a probability and NOT calibrated against outcomes — nothing in this repository
has measured how often a 0.8 hypothesis is correct. ``Hypothesis.score_basis``
carries that caveat into every record so it travels with the number.

Metrics for this stage are reported as top-1 candidate accuracy and top-3
candidate coverage, deliberately not as diagnosis accuracy: getting the right
fault into the candidate set is a different claim from producing a correct
diagnosis, which also requires the validation and recommendation stages.

The LLM's remaining role
------------------------
It receives this ranked set and may reorder it, explain it, or say the evidence is
insufficient. If it names a fault outside the set, ``classify_llm_fault()`` marks
the result UNSUPPORTED_HYPOTHESIS. Such a hypothesis is not discarded — a model
noticing something the rules missed is worth surfacing — but it is labelled, so it
can never be mistaken for a hypothesis the evidence produced.
"""

